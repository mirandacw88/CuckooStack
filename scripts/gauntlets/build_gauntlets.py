#!/usr/bin/env python3
"""Builds src/core/GauntletLayouts.inc, the gauntlets Gauntlets.cpp includes, from their grids: assets/gauntlets/<name>.txt,
rows top first (Gauntlet.h's cells), the ';' lines at the top its description (carried into the .inc as comments).
The grids are what ships: tune them in the level editor (tools/level_editor), which saves through here, or by hand.

    python3 scripts/gauntlets/build_gauntlets.py                 writes the .inc from the grids
    python3 scripts/gauntlets/build_gauntlets.py --print NAME    prints a grid's rows
    python3 scripts/gauntlets/build_gauntlets.py --draft NAME    writes assets/gauntlets/NAME.txt from its first draft
                                                                 (NAME.py here: NAME, LEVEL, build() on a kit.Grid, a
                                                                 docstring); --force to overwrite a grid (its tuning lost)

Check a grid with build/gauntlet_check --file assets/gauntlets/NAME.txt: its one way through, its near misses, the
meter. The ctest "scripts" test checks the .inc is what the grids build.
"""
import glob
import importlib
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
GRIDS = os.path.join(ROOT, "assets", "gauntlets")
OUT = os.path.join(ROOT, "src", "core", "GauntletLayouts.inc")
DRAFTS = ["tomb", "gallery", "wells", "labyrinth", "ascent"]  # (the first drafts, by level)

sys.path.insert(0, HERE)


def read_grid(path):
    """a grid file: (its description's lines, its rows top first)"""
    description, rows = [], []
    with open(path) as f:
        for line in f.read().splitlines():
            if line.startswith(";"):
                description.append(line[1:][1:] if line[1:2] == " " else line[1:])
            elif line.strip():
                rows.append(line.rstrip())
    return description, rows


def grid_text(description, rows):
    return "".join("; %s\n" % line if line else ";\n" for line in description) + "".join(row + "\n" for row in rows)


def write_grid(path, description, rows):
    with open(path, "w") as f:
        f.write(grid_text(description, rows))


def grids(folder=GRIDS):
    """every grid: (name, description, rows), by name"""
    out = []
    for path in sorted(glob.glob(os.path.join(folder, "*.txt"))):
        description, rows = read_grid(path)
        out.append((os.path.splitext(os.path.basename(path))[0], description, rows))
    return out


def render(folder=GRIDS):
    lines = ["// Generated by scripts/gauntlets/build_gauntlets.py from the grids in assets/gauntlets. Do not edit: tune a",
             "// grid (tools/level_editor) and re-run it. The gauntlets, by name: each one's grid, its rows top first (Gauntlet.h)."]
    for name, description, rows in grids(folder):
        lines.append("")
        lines += ["// " + line if line else "//" for line in description]
        lines.append('{"%s", {' % name)
        lines += ['    "%s",' % row for row in rows]
        lines.append("}},")
    return "\n".join(lines) + "\n"


def draft(name):
    """a first draft's (description, rows)"""
    mod = importlib.import_module(name)
    return mod.__doc__.strip().splitlines(), mod.build().rows_top_first()


def main():
    args = sys.argv[1:]
    if len(args) == 2 and args[0] == "--print":
        print("\n".join(read_grid(os.path.join(GRIDS, args[1] + ".txt"))[1]))
        return
    if args and args[0] == "--draft" and len(args) >= 2:
        path = os.path.join(GRIDS, args[1] + ".txt")
        if os.path.exists(path) and "--force" not in args:
            sys.exit("%s exists (tuned, maybe): --force to overwrite it with the draft" % os.path.relpath(path, ROOT))
        write_grid(path, *draft(args[1]))
        print("%s: from its draft" % os.path.relpath(path, ROOT))
        return
    out = args[0] if args else OUT
    with open(out, "w") as f:
        f.write(render())
    print("%s: %s" % (os.path.relpath(out, ROOT), ", ".join(name for name, _, _ in grids())))


if __name__ == "__main__":
    main()
