#!/usr/bin/env python3
"""Builds src/core/LevelLayouts.inc, the campaign's levels LevelCatalog.cpp includes, from their files: assets/levels/level_NN.txt
(LevelData.h has the format: the course wall by wall, its saws and disco balls, its finish line, difficulty and raids).
The files are what ships: tune them in the level editor (tools/level_editor), which saves through here, or by hand.

    python3 scripts/levels/build_levels.py                writes the .inc from the files
    python3 scripts/levels/build_levels.py --bake N ...   writes level N's file as the generator lays it (build/level_check
                                                          --bake: its seed, length, saws and gauntlet); --force to overwrite
                                                          one (its tuning lost)

Check a level with build/level_check --file assets/levels/level_NN.txt --level N (--game: the bot plays it). The ctest
"scripts" test checks the .inc is what the files build.
"""
import glob
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
LEVELS = os.path.join(ROOT, "assets", "levels")
OUT = os.path.join(ROOT, "src", "core", "LevelLayouts.inc")
NAME = re.compile(r"^level_(\d+)\.txt$")


def path_of(n, folder=LEVELS):
    return os.path.join(folder, "level_%02d.txt" % n)


def levels(folder=LEVELS):
    """every level file: (number, its text), by number"""
    out = []
    for path in glob.glob(os.path.join(folder, "level_*.txt")):
        m = NAME.match(os.path.basename(path))
        if m:
            with open(path) as f:
                out.append((int(m.group(1)), f.read()))
    return sorted(out)


def render(folder=LEVELS):
    lines = ["// Generated by scripts/levels/build_levels.py from the levels in assets/levels. Do not edit: tune a level",
             "// (tools/level_editor) and re-run it. The levels, by number: each one's file (LevelData.h)."]
    for n, text in levels(folder):
        if ")LEVEL\"" in text:
            raise ValueError("level %d's file can't hold )LEVEL\"" % n)
        lines.append('{%d, R"LEVEL(%s)LEVEL"},' % (n, text))
    return "\n".join(lines) + "\n"


def write(out=OUT, folder=LEVELS):
    with open(out, "w") as f:
        f.write(render(folder))


def fmt(v):
    """a number as LevelData.cpp writes it: to the millimetre, no trailing zeros"""
    s = ("%.3f" % v).rstrip("0").rstrip(".")
    return "0" if s == "-0" else s


COURSE_LINE = re.compile(r"^(\s*)(\d+)(\s+)0(\s+)gauntlet(\s+)([a-z][a-z0-9_]*)\s*$")


def gauntlets_in(text):
    """the gauntlets a level's course lays, in order"""
    part, out = None, []
    for line in text.split("\n"):
        word = line.split(";")[0].strip()
        if word in ("course", "saws", "discos"):
            part = word
            continue
        m = COURSE_LINE.match(line.split(";")[0])
        if part == "course" and m:
            out.append(m.group(6))
    return out


def refit(text, name, width, build=os.path.join(ROOT, "build")):
    """the level's text with the named gauntlet's span made `width` cells wide (its grid grown or shrunk): what's after
    it (hazards, the finish line) moved on or back with it; every other line as it was. The game's own refit does it
    (build/level_check --refit: src/editor/LevelMerge.cpp, the iPhone and iPad editor's too)"""
    checker = os.path.join(build, "level_check")
    if not os.path.exists(checker):
        raise RuntimeError("build/level_check isn't built (cmake --build build --target level_check): it refits levels")
    done = subprocess.run([checker, "--refit", name, str(width), "--file", "-"], input=text, capture_output=True, text=True, timeout=60)
    if done.returncode != 0:
        raise RuntimeError("level_check --refit failed: " + done.stderr.strip())
    return done.stdout


def bake(n, build=os.path.join(ROOT, "build"), gauntlet=None):
    args = [os.path.join(build, "level_check"), "--bake", str(n)] + (["--gauntlet", gauntlet] if gauntlet else [])
    return subprocess.run(args, check=True, capture_output=True, text=True).stdout


def main():
    args = sys.argv[1:]
    if args and args[0] == "--bake":
        force = "--force" in args
        for a in args[1:]:
            if a == "--force":
                continue
            n = int(a)
            path = path_of(n)
            if os.path.exists(path) and not force:
                sys.exit("%s exists (tuned, maybe): --force to overwrite it with the generator's" % os.path.relpath(path, ROOT))
            with open(path, "w") as f:
                f.write(bake(n))
            print("%s: baked" % os.path.relpath(path, ROOT))
        return
    write(args[0] if args else OUT)
    print("%s: levels %s" % (os.path.relpath(args[0] if args else OUT, ROOT), ", ".join(str(n) for n, _ in levels())))


if __name__ == "__main__":
    main()
