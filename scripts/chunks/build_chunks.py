#!/usr/bin/env python3
"""Builds src/core/ChunkLayouts.inc, the chunks LevelCatalog.cpp includes, from their files: assets/chunks/<id>.txt
(Chunk.h has the format: a header of ranges, weight, uses and mirror, then the body). The chunks are the designer's set
pieces: the generators place them, and the game's own generated levels (31 and up) hold the ones whose ranges cover them.
The files are what ships: build them in the chunk editor (the iPad's Cuckoo Editor), which syncs them here, or by hand.

    python3 scripts/chunks/build_chunks.py     writes the .inc from the files

It only ever reads assets/chunks; it never bakes levels or gauntlets. The level editor's server runs it after a chunk
push. The ctest "scripts" test checks the .inc is what the files build.
"""
import glob
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
CHUNKS = os.path.join(ROOT, "assets", "chunks")
OUT = os.path.join(ROOT, "src", "core", "ChunkLayouts.inc")
ID = re.compile(r"^[a-z0-9_-]{1,60}$")  # (Chunk.cpp's validId)


def valid_id(chunk_id):
    return isinstance(chunk_id, str) and bool(ID.match(chunk_id))


def path_of(chunk_id, folder=CHUNKS):
    return os.path.join(folder, chunk_id + ".txt")


def chunks(folder=CHUNKS):
    """every chunk file: (id, its text), by id (a file whose name isn't an id is left out)"""
    out = []
    for path in glob.glob(os.path.join(folder, "*.txt")):
        chunk_id = os.path.basename(path)[:-4]
        if valid_id(chunk_id):
            with open(path) as f:
                out.append((chunk_id, f.read()))
    return sorted(out)


def render(folder=CHUNKS):
    lines = ["// Generated by scripts/chunks/build_chunks.py from the chunks in assets/chunks. Do not edit: build a chunk",
             "// (the iPad chunk editor, synced) and re-run it. The chunks, by id: each one's file (Chunk.h)."]
    for chunk_id, text in chunks(folder):
        if ")CHUNK\"" in text:
            raise ValueError("chunk %s's file can't hold )CHUNK\"" % chunk_id)
        lines.append('{"%s", R"CHUNK(%s)CHUNK"},' % (chunk_id, text))
    return "\n".join(lines) + "\n"


def write(out=OUT, folder=CHUNKS):
    with open(out, "w") as f:
        f.write(render(folder))


if __name__ == "__main__":
    write()
    print("wrote %s (%d chunks)" % (os.path.relpath(OUT, ROOT), len(chunks())))
